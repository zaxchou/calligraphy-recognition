# -*- coding: utf-8 -*-
"""将 Phase 2 学习成果整合到生产环境 qichengzhuanhe.py"""
import os

TARGET = os.path.join(os.path.dirname(__file__), '..', 'app', 'modules', 'pantianshou_composition', 'qichengzhuanhe.py')
with open(TARGET, 'r', encoding='utf-8') as f:
    c = f.read()

log = []

# === 1. 起的硬规则第2条：增加"单边单点"约束 ===
OLD_QI_RULE2 = '''2. **起必须在画面边缘（x≤5 或 x≥95 或 y≤5 或 y≥95）且该位置有明确笔墨** —— 不在画面中央（x和y均在20-80间），不在留白处。起可以从画外开始，但交汇点必须落在边缘笔墨上。**严禁将"从右下边缘入画"误解为"起必须在右下角"；必须根据画材实际入画方向确定交汇点：若主干延长线从左边缘穿出，起就在左边缘；若从上边缘穿出，起就在上边缘。**'''

NEW_QI_RULE2 = '''2. **起必须满足"单边单点"铁律**：起的一维坐标必须严格在边缘（x≤5 或 x≥95 或 y≤5 或 y≥95），但**另一维坐标必须在5-95之间**（如x=85,y=45是合法的；x=95,y=95是非法的）。**严禁取画面角落双极值！** 起点由主干延长线与边缘的几何交点唯一确定，与方位描述词无关。**严禁将"从右下边缘入画"误解为"起必须在右下角"；必须根据画材实际入画方向确定交汇点：若主干延长线从右边缘中段穿出，起就在右边缘中段（如x=85,y=45），而非右下角。**'''

if OLD_QI_RULE2 in c:
    c = c.replace(OLD_QI_RULE2, NEW_QI_RULE2)
    log.append('OK 起单边单点约束')
else:
    log.append('SKIP 起规则未匹配')

# === 2. 承：增加面积中心量化要求 ===
OLD_CHENG = '''- **承必须是从起出发后，沿生长方向遇到的第一个、面积最大、笔墨最实的画材实体的面积中心点**（视觉重心，非边缘），且**必须与起属于同一画材、同一生长链**。'''

NEW_CHENG = '''- **承必须是从起出发后，沿生长方向遇到的第一个、面积最大、笔墨最实的画材实体的面积中心点**（视觉重心，非边缘），且**必须与起属于同一画材、同一生长链**。**承点必须落在目视估算面积占比>40%的核心区块中心**，不可标在线条端点、墨点或次要附属物上。'''

if OLD_CHENG in c:
    c = c.replace(OLD_CHENG, NEW_CHENG)
    log.append('OK 承面积中心量化')
else:
    log.append('SKIP 承规则未匹配')

# === 3. 禁止行为：增加双极值禁止 ===
OLD_FORBID = '''**⚠️ 绝对禁止行为（违反任一即判定错误）**：
- 起不在边缘、起在留白、起在花头/叶尖/题跋；起未通过墨线延长线验证；'''

NEW_FORBID = '''**⚠️ 绝对禁止行为（违反任一即判定错误）**：
- **起取双极值（x≥90且y≥90 或 x≤10且y≤10 等）—— 这是最常见的致命错误，起的两个坐标绝不可同时接近画面角落**；
- 起不在边缘、起在留白、起在花头/叶尖/题跋；起未通过墨线延长线验证；'''

if OLD_FORBID in c:
    c = c.replace(OLD_FORBID, NEW_FORBID)
    log.append('OK 禁止双极值')
else:
    log.append('SKIP 禁止行为未匹配')

# === 4. 追加 few-shot 示例到 prompt 末尾 ===
FEWSHOT = '''

---

**📚 Few-Shot 示例（以下是人工标注的正确范例，请严格参考其标注逻辑）**

### 示例1：雏鸡+山石图
- 起 (85, 45)：山石主干水平延伸至右边缘，起在右边缘中段（非右下角），另一维y=45∈[5,95]
- 承 (70, 35)：雏鸡躯干面积中心（占比>40%的核心区块），从起向上生长Δy=-10
- 转 (30, 60)：山石区域视觉张力峰值，承→转方向突变>45°
- 合 (10, 20)：左上角印章区域，转→合与起→承形成闭环

### 示例2：蒲扇图
- 起 (85, 95)：蒲扇柄基座在底部边缘，y=95在边缘，x=85∈[5,95]
- 承 (70, 70)：蒲扇主体面积中心，从起向上生长Δy=-25
- 转 (35, 45)：花茎分叉处，墨色最浓的视觉张力峰值
- 合 (80, 15)：右上题跋区域，转→合与起→承形成几何闭环

**关键规律**：起永远不是角落(95,95)；承永远在最大实体中心；转永远在链末端；合永远追随印章。'''

OLD_END = '不可凭经验惯性或构图直觉设定**"""'
NEW_END = '不可凭经验惯性或构图直觉设定**' + FEWSHOT + '"""'

if OLD_END in c:
    c = c.replace(OLD_END, NEW_END)
    log.append('OK few-shot appended')
else:
    log.append('SKIP few-shot 未匹配')

with open(TARGET, 'w', encoding='utf-8') as f:
    f.write(c)

for l in log:
    print(f'  {l}')
print(f'Done: {TARGET}')
