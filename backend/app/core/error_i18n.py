def translate_detail(detail: Any, request) -> Any:
    """Accept-Language 以 en 开头时翻译中文 detail；其余原样返回。"""
    if not isinstance(detail, str):
        return detail
    try:
        lang = (request.headers.get("accept-language") or "").lower()
    except Exception:
        return detail
    if not lang.startswith("en"):
        return detail
    return _ZH_TO_EN.get(detail, detail)
