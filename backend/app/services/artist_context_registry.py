ARTIST_BIRTH_YEARS = {
    "李鱓": 1686,
    "郑燮": 1693,
    "金农": 1687,
    "黄慎": 1687,
    "边寿民": 1684,
    "刘海勇": 1976,
}


def get_artist_birth_year(artist_name: str) -> Optional[int]:
    """
    获取画家的出生年份
    
    Args:
        artist_name: 画家名字
    
    Returns:
        出生年份，未找到返回 None
    """
    if not artist_name:
        return None
    
    # 精确匹配
    if artist_name in ARTIST_BIRTH_YEARS:
        return ARTIST_BIRTH_YEARS[artist_name]
    
    # 模糊匹配（处理"清_李鱓"等格式）
    for key, year in ARTIST_BIRTH_YEARS.items():
        if key in artist_name or artist_name in key:
            return year
    
    return None


