def get_artist_context(artist_name: str) -> str:
    """
    获取画家的背景上下文
    
    Args:
        artist_name: 画家名字（如"李鱓"、"郑燮"）
    
    Returns:
        画家背景上下文字符串，如果未找到则返回通用模板
    """
    if not artist_name:
        return GENERIC_ARTIST_CONTEXT_TEMPLATE.format(artist_name="未知画家")
    
    # 精确匹配
    if artist_name in ARTIST_CONTEXTS:
        return ARTIST_CONTEXTS[artist_name]
    
    # 模糊匹配（处理"清_李鱓"等格式）
    for key, context in ARTIST_CONTEXTS.items():
        if key in artist_name or artist_name in key:
            return context
    
    # 未找到，返回通用模板
    return GENERIC_ARTIST_CONTEXT_TEMPLATE.format(artist_name=artist_name)


def get_artist_display_name(artist_name: str) -> str:
    """
    获取画家的显示名称（去除朝代前缀等）
    
    Args:
        artist_name: 原始画家名字（如"清_李鱓"、"李鱓"）
    
    Returns:
        清理后的显示名称
    """
    if not artist_name:
        return "未知画家"
    
    # 去除常见朝代前缀
    prefixes = ["清_", "明_", "宋_", "元_", "唐_", "近代_", "现代_"]
    for prefix in prefixes:
        if artist_name.startswith(prefix):
            return artist_name[len(prefix):]
    
    return artist_name
